def get_quiz_categories():
    return sorted({q["category"] for q in RUSSIAN_QUIZ})

def get_random_questions(amount=10, category=None):
    pool = [q for q in RUSSIAN_QUIZ if not category or q["category"] == category]
    if not pool:
        return []
    if len(pool) < amount:
        amount = len(pool)
    return random.sample(pool, amount)

def format_question(question_data):
    text = f"❓ {question_data['question']}\n\n"
    for i, opt in enumerate(question_data['options']):
        text += f"{i+1}. {opt}\n"
    return text, question_data['answer']

